"""학교명 → 고입 유형 분류기 (시기 슬롯 구조 공용).

키워드로 못 잡는 학교(자사고는 이름에 '자사'가 없다)는
SCHOOL_TYPE_OVERRIDES에 등록한다. 미분류("")는 sync가 '확인필요'로
플래그하므로, 플래그가 뜰 때마다 여기에 추가하면 된다.
"""

# ponytail: 수동 사전 = 미분류 플래그가 뜰 때 채우는 calibration knob
SCHOOL_TYPE_OVERRIDES: dict[str, str] = {
    "하나고": "자사고",
    "민족사관고": "자사고",
    "민사고": "자사고",
    "상산고": "자사고",
    "외대부고": "자사고",
    "북일고": "자사고",
    "인천하늘고": "자사고",
}

# 순서 중요: 먼저 매칭되는 키워드가 이긴다 (영재 > 과학, 국제중학교 같은 오탐 없음)
_KEYWORD_RULES = [
    ("영재", "영재고"),
    ("과학고", "과학고"),
    ("과고", "과학고"),
    ("예술", "예술계고"),
    ("예고", "예술계고"),
    ("체육", "예술계고"),
    ("체고", "예술계고"),
    ("마이스터", "특성화고"),
    ("외국어", "외고/국제고"),
    ("외고", "외고/국제고"),
    ("국제고", "외고/국제고"),
]


def classify_school(name: str) -> str:
    """학교명에서 유형 표준값을 판정한다. 미분류는 ""."""
    cleaned = str(name).strip()
    if not cleaned:
        return ""
    # 등학교 제거: "고등학교" -> "고"
    base = cleaned.replace("등학교", "").rstrip()
    for key, type_name in SCHOOL_TYPE_OVERRIDES.items():
        if key in base:
            return type_name
    for keyword, type_name in _KEYWORD_RULES:
        if keyword in base:
            return type_name
    return ""


# ─────────────────────────────────────────────────────────────
# 학교명 표준화 (신목고 / 신목고등학교 / 신목 → 신목고)
# ─────────────────────────────────────────────────────────────

# "아직 안 정했다"는 뜻으로 담임이 넣는 값들. 학교명이 아니다.
_PLACEHOLDERS = {"ㅇ", "o", "O", "○", "0", "x", "X", "-", "미정", "고민중", "없음", "미진학"}

# 꼬리표 통일: 긴 표기 → 통용 표기. 순서 중요(등학교를 먼저 털어낸다).
_SUFFIX_RULES = [
    ("등학교", ""),      # 고등학교 → 고
    ("등학고", ""),      # 오타: 대구과학고등학고 → 대구과학고
    ("등하교", ""),      # 오타: 영상고등하교 → 영상고
    ("외국어고", "외고"),
    ("과고", "과학고"),
    ("여자고", "여고"),
    ("예술고", "예고"),
    ("체육고", "체고"),
]

# 규칙으로 못 잡는 개별 학교. 미표준 플래그가 뜰 때 여기 추가한다.
# ponytail: 규칙 + 예외사전. 92종 전부를 사전에 박지 않는다.
SCHOOL_NAME_ALIASES: dict[str, str] = {
    "신목": "신목고",
}

_MULTI_SEPARATORS = (",", "/", "·", "、")


def normalize_school(name: str) -> str:
    """원문 학교명 → 표준 학교명.

    판단 불가(플레이스홀더 / 복수 기재)는 "" 을 돌려준다 — 틀린 학교로
    집계되느니 세지 않는 편이 낫다.
    """
    s = str(name).strip()
    if not s or s in _PLACEHOLDERS:
        return ""

    # "O(하나고 고민)" 처럼 플레이스홀더로 시작하는 메모
    if s[0] in "OoO○ㅇ" and len(s) > 1 and s[1] in "( ":
        return ""

    # 복수 기재("신목고, 양정고", "진명여고 목동고 금옥고")는 하나로 못 줄인다
    if any(sep in s for sep in _MULTI_SEPARATORS) or s.count("고") > 1 and " " in s:
        return ""

    # 복수기재 판정을 마친 뒤에 공백을 턴다 ("한성 과학 고" → "한성과학고")
    s = "".join(s.split())
    if s in _PLACEHOLDERS:
        return ""

    for old, new in _SUFFIX_RULES:
        if s.endswith(old):
            s = s[: -len(old)] + new

    if s in SCHOOL_NAME_ALIASES:
        return SCHOOL_NAME_ALIASES[s]

    # 꼬리표가 통째로 빠진 입력(신목) 보정
    if not s.endswith(("고", "학교")):
        s += "고"
    return s


# ─────────────────────────────────────────────────────────────
# 학생부(생기부) 점검 대상 판정
# ─────────────────────────────────────────────────────────────

# ⚠ 아래 값은 연수자료 원문으로 반드시 검증할 것. 저장소에 원문이 없어
#    통용 규정으로 초안을 잡았다. 틀린 항목은 이 표만 고치면 된다.
# ponytail: 판정 로직이 아니라 표를 고치게 만든다 — 해마다 바뀌는 건 값이지 코드가 아니다.
RECORD_RULES: dict[str, dict[str, str]] = {
    "영재고":     {"제출": "O", "반영학기": "3-1", "출력유형": "과고·영재고"},
    "과학고":     {"제출": "O", "반영학기": "3-1", "출력유형": "과고·영재고"},
    # 전국단위/서울 광역단위는 학생부 출력 방식이 다르다. 학교를 모르면 찍지 않는다.
    "자사고":     {"제출": "O", "반영학기": "3-1", "출력유형": "자사고(전국/서울 확인)"},
    "외고/국제고": {"제출": "O", "반영학기": "3-2", "출력유형": "외고·국제고"},
    "예술계고":   {"제출": "O", "반영학기": "3-2", "출력유형": "예체능"},
    "특성화고":   {"제출": "O", "반영학기": "3-2", "출력유형": "특성화·마이스터"},
    "일반고":     {"제출": "X", "반영학기": "", "출력유형": ""},
    "기타/대안":  {"제출": "확인필요", "반영학기": "", "출력유형": ""},
}

# 서울 광역단위 자사고는 전국단위와 출력 방식이 다르다.
SEOUL_JASA = {"이화여고", "한가람고", "장훈고", "경희고", "중동고", "세화고", "배재고", "선덕고"}

# 전국단위 자사고 (SCHOOL_TYPE_OVERRIDES와 짝을 이룬다)
NATIONWIDE_JASA = {"하나고", "상산고", "민족사관고", "민사고", "외대부고", "북일고", "인천하늘고"}


def record_requirement(hope_type: str, school: str = "") -> dict[str, str]:
    """지원 유형(+학교)에서 학생부 제출 여부와 점검 기준을 판정한다.

    반환: {"제출", "반영학기", "출력유형", "점검필요"}
    """
    rule = dict(RECORD_RULES.get(str(hope_type).strip(), {
        "제출": "확인필요", "반영학기": "", "출력유형": "",
    }))

    std = normalize_school(school)
    if hope_type == "자사고" and std:
        if std in SEOUL_JASA:
            rule["출력유형"] = "서울자사"
        elif std in NATIONWIDE_JASA:
            rule["출력유형"] = "전국자사"

    rule["점검필요"] = "O" if rule["제출"] == "O" else ""
    return rule
